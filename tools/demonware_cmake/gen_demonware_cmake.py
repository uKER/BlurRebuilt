#!/usr/bin/env python3
"""[Blur2PC][x64] Generate cmake/demonware.cmake from the DemonWare 2.0 VS2005 projects.

The shipped DemonWare libraries under code/vendor/demonware/2.0/lib exist only as
x86 (win32-vs8), so the x64 build compiles the same libraries from the bundled
sources. The source lists and preprocessor definitions come from each project's
`Release-mt|Win32` configuration, exactly as demonware-win32-vc8.sln built them;
curl comes from external/curl-7.19.2/lib/bdLibcurl.vcproj. OpenSSL 0.9.8i is not
in the tree (only its headers and x86 libs are); tools/demonware_cmake/
build_openssl_x64.cmd builds it, and the generated file links the result.

Usage (from the worktree root):
    python tools/demonware_cmake/gen_demonware_cmake.py --out cmake/demonware.cmake
"""
import argparse
import re
from pathlib import Path

DW = "code/vendor/demonware/2.0"

# Library name -> project file, in the order Amax links them (blur_common.cmake).
PROJECTS = [
    ("bdConnection", "bdConnection/bdConnection-win32-vc8.vcproj"),
    ("bdCore", "bdCore/bdCore-win32-vc8.vcproj"),
    ("bdLobby", "bdLobby/bdLobby-win32-vc8.vcproj"),
    ("bdSocket", "bdSocket/bdSocket-win32-vc8.vcproj"),
    ("bdPlatform", "bdPlatform/bdPlatform-win32-vc8.vcproj"),
    ("bdNet", "bdNet/bdNet-win32-vc8.vcproj"),
    ("bdExampleCommonLobby", "bdExample/bdExampleCommonLobby/bdExampleCommonLobby-win32-vc8.vcproj"),
    ("libcurl", "external/curl-7.19.2/lib/bdLibcurl.vcproj"),
]
CONFIG = "Release-mt|Win32"


def parse(top: Path, rel: str):
    path = top / DW / rel
    text = path.read_text(encoding="latin-1")
    cfg = re.search(r'<Configuration\s+Name="%s"(.*?)</Configuration>' % re.escape(CONFIG), text, re.S)
    if not cfg:
        raise SystemExit(f"{rel}: no {CONFIG} configuration")
    tool = re.search(r'Name="VCCLCompilerTool"(.*?)/>', cfg.group(1), re.S).group(1)
    defs = re.search(r'PreprocessorDefinitions="([^"]*)"', tool).group(1)
    incs = re.search(r'AdditionalIncludeDirectories="([^"]*)"', tool).group(1)
    if "ExcludedFromBuild" in text:
        raise SystemExit(f"{rel}: per-file exclusions are not handled")
    srcs = re.findall(r'RelativePath="([^"]+\.(?:cpp|c))"', text)
    base = path.parent
    src_paths = [(base / s.replace("\\", "/")).resolve().relative_to(top.resolve()).as_posix() for s in srcs]
    # The vcproj macros: only $(DXSDK_DIR) appears, for D3D headers DemonWare does not use on PC.
    inc_paths = []
    for i in incs.replace("&quot;", "").split(";"):
        i = i.strip()
        if not i or "$(" in i:
            continue
        p = (base / i.replace("\\", "/")).resolve().relative_to(top.resolve()).as_posix()
        if "openssl-0.9.8i/include" in p:
            continue  # x86 opensslconf.h; the x64 build's own headers replace it
        inc_paths.append(p)
    def_list = [d.strip() for d in defs.split(",") if d.strip()]
    return src_paths, inc_paths, def_list


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--top", default=".")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    top = Path(args.top)
    L = [
        "# [Blur2PC][x64] GENERATED by tools/demonware_cmake/gen_demonware_cmake.py",
        "# from the DemonWare 2.0 Release-mt|Win32 project settings; do not edit by hand.",
        "# Included by blur_common.cmake when BLUR_X64 is set; needs BLUR_OPENSSL_X64.",
        "",
    ]
    for name, rel in PROJECTS:
        srcs, incs, defs = parse(top, rel)
        tgt = f"dw_{name}"
        L.append(f"add_library({tgt} STATIC")
        L += [f"    ${{BLUR_TOP}}/{s}" for s in srcs]
        L.append(")")
        L.append(f"set_target_properties({tgt} PROPERTIES OUTPUT_NAME {name} FOLDER \"vendor/demonware\")")
        L.append(f"target_include_directories({tgt} PRIVATE")
        L += [f"    ${{BLUR_TOP}}/{i}" for i in incs]
        L.append("    ${BLUR_OPENSSL_X64}/include)")
        L.append(f"target_compile_definitions({tgt} PRIVATE {' '.join(defs)})")
        # Third-party code at its own warning level; the game's global /W3 list stays.
        L.append(f"target_compile_options({tgt} PRIVATE /W1)")
        L.append("")
    Path(args.out).write_text("\n".join(L) + "\n", newline="\r\n")
    print(f"wrote {args.out}: {len(PROJECTS)} libraries")


if __name__ == "__main__":
    main()
