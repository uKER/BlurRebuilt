#!/usr/bin/env python3
"""
cpgen.py — regenerate the shader-constant headers that Bizarre's `CPFile`
Jam rule produced from .cp (pixel constants), .cv (vertex constants) and
.sp (sampler) files.

Input format (one name per line, `//` comments, blank lines ignored):
  #set N        counter = N            #begin N   counter = N
  #end          no-op                  #align N   counter rounded up to a multiple of N
  #skip N       counter += N           #include "rel\path.cp"  emit that file first (numbering continues)
  NAME          -> #define NAME <n>  and  #define <P>NAME <r><n>   (n = counter, counter += 1)

<P> and <r>: .cp/.cv -> 'C' and 'c' (constant register), .sp -> 'S' and 's' (sampler register).
Reference output: code/tools/spt_billboard/source/spt_billboard/shaders/{ps,vs}Constants.h

Usage: python cpgen.py <file.cp|.cv|.sp>...   (writes <file>.h next to each input)
       python cpgen.py --from-json _work/build/targets_pc_speed.json
"""
import json
import os
import re
import sys


def parse(path, counter, out, stack):
    kind = os.path.splitext(path)[1].lower()
    letter, reg = ('S', 's') if kind == '.sp' else ('C', 'c')
    with open(path, 'r', encoding='latin-1') as fh:
        for raw in fh:
            line = raw.split('//', 1)[0].strip()
            if not line:
                continue
            if line.startswith('#'):
                parts = line.split()
                d = parts[0].lower()
                arg = int(parts[1]) if len(parts) > 1 and parts[1].lstrip('-').isdigit() else None
                if d in ('#set', '#begin') and arg is not None:
                    counter = arg
                elif d == '#align' and arg:
                    counter = (counter + arg - 1) // arg * arg
                elif d == '#skip' and arg is not None:
                    counter += arg
                elif d == '#include':
                    inc = line[len('#include'):].strip().strip('"').replace('\\', '/')
                    incp = os.path.normpath(os.path.join(os.path.dirname(path), inc))
                    if os.path.normcase(incp) in stack:
                        raise RuntimeError(f'include cycle at {incp}')
                    counter = parse(incp, counter, out, stack | {os.path.normcase(incp)})
                # '#end', '#endif' and anything else: ignored
                continue
            name = line.split()[0]
            if not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', name):
                raise RuntimeError(f'{path}: bad constant name {name!r}')
            out.append(f'#define {name} {counter}')
            out.append(f'#define {letter}{name} {reg}{counter}')
            counter += 1
    return counter


def generate(path):
    out = []
    parse(path, 0, out, {os.path.normcase(path)})
    hpath = os.path.splitext(path)[0] + '.h'
    text = '// Generated by tools/jam2cmake/cpgen.py from ' + os.path.basename(path) + ' - do not edit\n' + '\n'.join(out) + '\n'
    if os.path.exists(hpath) and open(hpath, 'r', encoding='latin-1').read() == text:
        return hpath, False
    with open(hpath, 'w', encoding='ascii', newline='\n') as fh:
        fh.write(text)
    return hpath, True


def main():
    args = sys.argv[1:]
    files = []
    if args and args[0] == '--from-json':
        d = json.load(open(args[1], encoding='utf-8'))
        top = d['config']['top']
        files = [os.path.join(top, c['file']) for c in d['cpfiles']]
    else:
        files = args
    written = 0
    for f in files:
        h, changed = generate(f)
        written += changed
        print(('wrote   ' if changed else 'current ') + h)
    print(f'{len(files)} inputs, {written} headers written')


if __name__ == '__main__':
    main()
