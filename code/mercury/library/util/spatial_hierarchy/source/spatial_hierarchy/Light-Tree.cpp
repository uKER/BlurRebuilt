// build the KD-Tree containing the lights
void LightTree::Build()
{
	// create list of bounding boxes to pass into kd-tree builder
	Box3Vector primBounds;
	primBounds.Reserve(m_Primitives.Size());
	for (int i = 0; i < m_Primitives.Size(); i++)
	{
		Box3 *pBBox  = &((LightPrim*)m_Primitives[i])->m_bbox;

		primBounds.PushBack( *pBBox );
	}

	m_pBuilder = new KdBuilder (primBounds,
		100,	// intersect cost (high - raytracing an extra light is very expensive)
		0,		// traversal cost
		0.5f,	// empty bonus
		1,		// max primitives per leafnode
		-1		// max depth
		);

	// copy Nodes vector to a cache-aligned memory block
	m_nNodes = m_pBuilder->m_Nodes.Size()+1;
	m_pNodes = (KdNode*)BizAlignedMalloc(sizeof(KdNode) * (m_nNodes), 128);
	memcpy(m_pNodes+1, &m_pBuilder->m_Nodes[0], sizeof(KdNode) * m_pBuilder->m_Nodes.Size());

	// take ownership of the mailboxes generated by the builder, and delete the builder
	m_pMailboxes = m_pBuilder->m_pMailboxes;
	delete m_pBuilder;
	m_pBuilder = NULL;

	m_pRealMailBoxes = new int[m_Primitives.Size()];
	memset(m_pRealMailBoxes, 0, sizeof(int) * m_Primitives.Size());

	// free up the primitives
	for (int i=0; i<m_Primitives.Size(); i++)
		delete m_Primitives[i];
	m_Primitives.Clear();
	m_Primitives.Reserve(0);
}

