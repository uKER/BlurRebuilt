// --- light tree

LightTree::LightTree()
{
	m_pNodes = NULL;
	m_pBuilder = NULL;
	m_pMailboxes = NULL;
	m_pRealMailBoxes = NULL;

	m_LightPtrVec.Reserve(128);
}

// cleanup
LightTree::~LightTree()
{
	if (m_pNodes)
		BizAlignedFree(m_pNodes);
	if (m_pBuilder)
	{
		if (m_pBuilder->m_pMailboxes)
			delete m_pBuilder->m_pMailboxes;
		delete m_pBuilder;
	}

	if (m_pRealMailBoxes)
		delete m_pRealMailBoxes;
	
	if (m_pMailboxes)
		delete m_pMailboxes;

	// delete primitives
	for (int i=0; i<m_Primitives.Size(); i++)
		delete m_Primitives[i];
}

// add a light to the list of light primitives
void LightTree::AddLight(LUX::Light *pLight, const Box3 &bbox)
{
	LightPrim *pPrim = new LightPrim(m_LocalLights.Size(), bbox);
	m_Primitives.PushBack(pPrim);

	m_LocalLights.PushBack(pLight);
}

