MiniDumper::MiniDumper()
{
	// [Rog] We allocate a 10Mb buffer so we can free it up later to save a dump in low memory situations
	MEMORY_TRACKER_PUSH("mercury.tools_common.minidumper");
	g_bufferMemory = new U8[10 * 1024 * 1024];

	// firstly see if dbghelp.dll is around and has the function we need
	// look next to the EXE first, as the one in System32 might be old 
	// (e.g. Windows 2000)
	char szDbgHelpPath[_MAX_PATH];
	char* pSlash = NULL;

	if (GetModuleFileName( NULL, szDbgHelpPath, _MAX_PATH ))
	{
		pSlash = strrchr( szDbgHelpPath, '\\' );
		if (pSlash)
		{
			strcpy(g_szAppName, pSlash+1);
			strcpy( pSlash+1, "DBGHELP.DLL" );
			g_dbghelp = ::LoadLibrary( szDbgHelpPath );
		}
	}

	if (g_dbghelp==NULL)
	{
		// load any version we can
		g_dbghelp = ::LoadLibrary( "DBGHELP.DLL" );

		if (g_dbghelp==NULL)
		{
			LOGFATAL( g_pMyApplication->GetLogger(), "Failed to load DBGHELP.DLL\n");
		}
	}

	g_pDump = (MINIDUMPWRITEDUMP)::GetProcAddress( g_dbghelp, "MiniDumpWriteDump" );
	MEMORY_TRACKER_POP("mercury.tools_common.minidumper");
}

