// The structure is 12 bytes due to padding, but we only want to compare the first 11 bytes.
inline bool operator==(const gpuVertexElement& a, const gpuVertexElement& b)
{ return memcmp(&a, &b, 11) == 0; }

inline bool operator!=(const gpuVertexElement& a, const gpuVertexElement& b)
{ return memcmp(&a, &b, 11) != 0; }

