// gpuTexture
/**
	On Playstation3, gpuTexture can be used interchangeably with CellGcmTexture.  They have exactly the same memory format.
*/
class gpuTexture
{
public:
	gpuTexture() {}
	gpuTexture(const CellGcmTexture& v) : tex(v) {}
	gpuTexture(const gpuTexture& v) : tex(v.tex) {}
	gpuTexture& operator=(const CellGcmTexture& v) { tex = v; return *this; }
	gpuTexture& operator=(const gpuTexture& v) { tex = v.tex; return *this; }

	inline CellGcmTexture* GetGcmTexture() { return &tex; }

	inline int GetWidth() const 
	{ 
		return tex.width; 
	}
	inline int GetHeight() const 
	{ 
		return tex.height; 
	}
	inline int GetDepth() const 
	{ 
		return tex.depth; 
	}
	inline int GetLevels() const 
	{ 
		return tex.mipmap; 
	}
	inline gpuTextureFormat GetFormat() const 
	{ 
		return (gpuTextureFormat)GPU_TEXTURE_FORMAT(tex.format, tex.remap);
	}
	inline gpuTextureType GetType() const 
	{ 
		if (tex.cubemap) return GPU_TEXTURE_CUBE; 
		if (tex.dimension == CELL_GCM_TEXTURE_DIMENSION_3) return GPU_TEXTURE_VOLUME; 
		return GPU_TEXTURE_2D;
	}

	CellGcmTexture tex;
};

