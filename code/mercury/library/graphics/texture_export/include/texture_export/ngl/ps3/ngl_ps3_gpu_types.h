// Stream format for declaring vertex formats.
struct gpuVertexElement { u32 Type; u8 Usage; u8 UsageIndex; u8 Offset; u8 Freq; };
#define GPU_VERTEX_ELEMENT(stream,usage,index,format,offset) {(format)|(((stream)&0xFF)<<24), (usage), (index), (offset), 0}
#define GPU_VERTEX_ELEMENT_PS3(usage,index,format,offset,freq) {(format), (usage), (index), (offset), (freq)}
#define GPU_VERTEX_ELEMENT_END() {GPU_VERTEX_UNUSED, 0, 0, 0, 0}
#define GPU_VERTEX_ELEMENT_TYPE(elem) ((elem)->Type&0x00FFFFFF)
#define GPU_VERTEX_ELEMENT_STREAM(elem) ((elem)->Type>>24)
#define GPU_VERTEX_ELEMENT_USAGE(elem) ((elem)->Usage)
#define GPU_VERTEX_ELEMENT_USAGE_INDEX(elem) ((elem)->UsageIndex)

inline bool operator==(const gpuVertexElement& a, const gpuVertexElement& b)
{ return memcmp(&a, &b, sizeof(gpuVertexElement)) == 0; }

inline bool operator!=(const gpuVertexElement& a, const gpuVertexElement& b)
{ return memcmp(&a, &b, sizeof(gpuVertexElement)) != 0; }

