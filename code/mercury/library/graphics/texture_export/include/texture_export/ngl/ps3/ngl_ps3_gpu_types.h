// gpuSurface
/**
	On Playstation3, gpuSurface is a subset of the fields in CellGcmSurface (which controls all 4 MRT render targets plus depth).
	It contains all the common fields of CellGcmSurface (except x and y which are assumed to be 0), plus the specific fields for a 
	single render target (either color or depth).
*/
struct gpuSurface
{
	u8 type;        //< Surface memory layout.  Either CELL_GCM_SURFACE_PITCH or CELL_GCM_SURFACE_SWIZZLE.
	u8 antialias;   //< Antialiasing format.  See #gpuMultiSampleType.
	u8 location;    //< Data location.  Either CELL_GCM_LOCATION_MAIN or CELL_GCM_LOCATION_LOCAL.
	u8 depth;       //< 1 if this surface is a depth surface, else 0.
	u32 offset;     //< Data address.
	u32 format;     //< Surface memory format.  See #gpuSurfaceFormat.
	u16 width;      //< Surface width.
	u16 height;     //< Surface height.
	u32 pitch;      //< Number of bytes per row in memory.

	inline int GetWidth() const 
	{ 
		return width; 
	}
	inline int GetHeight() const 
	{ 
		return height; 
	}
	inline gpuSurfaceFormat GetFormat() const
	{
		return GPU_SURFACE_FORMAT(format, type==CELL_GCM_SURFACE_SWIZZLE, depth);
	}
};

