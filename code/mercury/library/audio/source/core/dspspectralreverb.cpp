//********************************
void Audio::Core::DSP::SpectralReverb::PolarToRectangularConversion(F32 * signal, int fftSize)
{
	//PolarToRectangularConversion (complex pairs)
	//x = r * cos * q, y = r * sin * q
	//input:
	//[MAG],[PHASE],[MAG],[PHASE]....	
	// output:
	//re(0),re(1),re(2),...,re(size/2),im(size/2-1),...,im(1)	

	int PVSize = fftSize/2;
	F32 *realBuffer = new F32 [PVSize];
	F32 *imagBuffer = new F32 [PVSize];

	//cian, change for ps3
	for (int i = 0,k=0; i <fftSize && k<PVSize; i +=2,k++)//nbr_points/2
	{
		
		F32 mag   = signal[i];
		F32 phase = signal[i+1];

		F32 real = mag * cos(phase);
		F32 imag =  mag * sin(phase);
		
		realBuffer[k] = real;
		imagBuffer[k] = imag;
		
	}

	//reorganize the output for the horrible FFT format
	//output of conversion, re(0),re(1),re(2),...,re(size/2),im(size/2-1),...,im(1)
	for (int i = 0; i < PVSize;  i++ )//nbr_points/2
	{
		signal[i] =		realBuffer[i];						
	}	

	signal[PVSize] = imagBuffer[0]; // imag[0] goes to signal[PVSize], see FFT output

	for (int i = 1; i < PVSize;  i++ )
	{
		signal[(fftSize) -i] =		imagBuffer[i];						
	}

	///for(int i = 0;i < frameSize;i++)
	//	printf("Output Value %d : %f\n",i,signal[i]);

	//printf( "PolarToRectangularConversion\n");
	

	delete [] realBuffer;
	delete [] imagBuffer;

}

void Audio::Core::DSP::SpectralReverb::Window(F32 * signal,int frameSize,WindowType eWindow,F32 fAmpGain)
{
	//const F32	pi		= 3.1415926535897932384626433832795;
	
	switch(eWindow)
	{
		case E_WINDOWTYPE_HAMMING:
		{
			for( int  w = 0;w< frameSize;w++)
			 {
				F32 coef1=((Maths::f2Pi*w)/frameSize);
				signal[w] *= (1-(0.54f + .46f*cos(coef1)))*fAmpGain;//hamming window
			 }
			 break;
		}

		case E_WINDOWTYPE_HANN:
		{
			for( int  w = 0;w< frameSize;w++)
			{
				F32 coef1=((Maths::f2Pi*w)/frameSize);
				signal[w] *= (/*1-*/(.5f * (1 - Maths::Cos(coef1))))*fAmpGain;//hamming window
			}
				
			 break;
		}

		//simple gain change
		case E_WINDOWTYPE_RECTANGULAR:
		{				
			for( int  w = 0;w< frameSize;w++)
			{
				 signal[w] *= fAmpGain;//hamming window		
			}

			 break;
		}
	}
}



