bool Audio::Core::DSP::SpectralReverb::Process(void* pFrameData, const ProcessInfo& info, bool bProcess)
{
	PERF_EVENT("Audio.Generate.DSP.SpectralReverb.Process");

#ifndef AUDIO_DISABLE_DSP

#if !defined (PLATFORM_PC)
//#if !defined (PLATFORM_PS3) && ! defined (PLATFORM_SPU)

		if( !m_bActive || bDisableAll )
		return true;
	
	//static bool doit = false;
	//if (doit)
	//	g_pWriter->Write((F32*)pFrameData, 1.f);


		//PERF_EVENT("Audio.ReverbUpdate");

#ifndef USING_STATIC_BUFFERS_FOR_DYNAMIC

	m_phaseBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Phase ];
	m_magBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Mag ];
	m_realBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Real ];
	m_imagBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Imag ];
	m_pTempBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Temp ];
	m_windowBuffer = &info.pDynamicBuffers[ m_uDynamicBuffer + m_uChannels * m_fftSize * DynamicBuffers_Window ];

#endif

	//init the buffers
	if(m_firstTimeProcessing)
	{

		m_sumBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Sum ];
		memset(m_sumBuffer,0,m_fftSize*sizeof(F32));

		m_pReverbBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * (m_fftSize) * Buffers_Reverb ];
		memset(m_pReverbBuffer,0,(m_fftSize)*sizeof(F32));

		m_pFilterBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * (m_fftSize) * Buffers_Filter ];
		memset(m_pFilterBuffer,0,(m_fftSize)*sizeof(F32));

		m_queueBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * (m_fftSize) * Buffers_Queue ];
		memset(m_queueBuffer,0,(m_fftSize)*sizeof(F32));

		////create the Hann window
		m_pHannBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Hann ];
		const ::Maths::HVec4 one(::Maths::Constants< ::Maths::HF32>::One());
		const ::Maths::HVec4 four(::Maths::Constants< ::Maths::HF32>::Four());
		const ::Maths::HVec4 half(::Maths::Constants< ::Maths::HF32>::Half());
		const ::Maths::HVec4 twoPi(::Maths::Constants< ::Maths::HF32>::Pi() * ::Maths::Constants< ::Maths::HF32>::Two());
		//for( int  w = 0;w< m_fftSize;w++)
		//{
		//	//m_pHannBuffer[w] = 1;
		//	F32 coef1=((Maths::f2Pi*w)/m_fftSize);
		//	m_pHannBuffer[w] = ((.5f * (1 - Maths::Cos(coef1))));//hann window
		//}

		const ::Maths::HF32 recipFFtSize(1.f/(F32)m_fftSize);
		::Maths::HVec4 wF(0.f, 1.f, 2.f, 3.f);
		for( int  w = 0;w< m_fftSize;w+=4, wF += four)
		{
			::Maths::HVec4 coef1=((twoPi*wF)*recipFFtSize);
			::Maths::HVec4 val(half * (one - ::Maths::Cos(coef1)));
			::Maths::Store(val, (MathsStorage::Float4*)&m_pHannBuffer[w]);
			//m_pHannBuffer[w] = 1;

			
			//m_pHannBuffer[w] = ((.5f * (1 - Maths::Cos(coef1))));//hann window
		}

#ifdef USING_STATIC_BUFFERS_FOR_DYNAMIC

		m_phaseBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Phase ];
		m_magBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Mag ];
		m_realBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Real ];
		m_imagBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Imag ];
		m_pTempBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * (m_fftSize) * Buffers_Temp ];
		m_windowBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * m_fftSize * Buffers_Window ];

#endif

		//memset(m_phaseBuffer,0,m_fftSize*sizeof(F32));
		//memset(m_magBuffer,0,m_fftSize*sizeof(F32));
		//memset(m_realBuffer,0,m_fftSize*sizeof(F32));
		//memset(m_imagBuffer,0,m_fftSize*sizeof(F32));
		//memset(m_pTempBuffer,0,m_fftSize*sizeof(F32));
		//memset(m_windowBuffer,0,m_fftSize*sizeof(F32));

		//create presets
		//for(int i = 0; i < E_ReverbPreset_Max;i++)
		//m_pPresetBuffer = &info.pStaticBuffers[ m_uBuffer + m_uChannels * (m_fftSize) * (Buffers_Preset) ];

		S32	currentPreset = m_preset;

		currentPreset = (S32)Maths::Clamp((F32)currentPreset,0.f,(F32)E_ReverbPreset_Max);
	
		PreparePresetBuffers((E_ReverbPresets)currentPreset);

		m_firstTimeProcessing = false;

		m_reverbParams.hopSize = m_fftSize / uFrameLength;

		m_queueBufferReadIndex = 0;

	}
	
	if( !m_bActive || bDisableAll )
		return true;
	
	F32* aSample = (F32*)pFrameData;
	static S32 queueBufferWrite = m_fftSize - uFrameLength;

	queueBufferWrite += uFrameLength;
	queueBufferWrite = queueBufferWrite % (m_fftSize);

	//copy the inputBuffer into the queueBuffer at the m_queueBufferReadIndex
	Frame::Copy(m_queueBuffer+m_queueBufferReadIndex,aSample);

	queueBufferWrite += uFrameLength;
	queueBufferWrite = queueBufferWrite % (m_fftSize);

	for(S32 uFrame = 0; uFrame < m_reverbParams.hopSize; uFrame++)
	{
		int iOffset = ( (uFrame*uFrameLength)+m_queueBufferReadIndex ) % m_fftSize;
		Frame::DoMultiply(m_windowBuffer+((uFrame*uFrameLength)),m_queueBuffer+(iOffset),m_pHannBuffer+((uFrame*uFrameLength)));
	}

	RealFFT_Split(m_windowBuffer,m_fftSize);

	////////////do reverb stuff here
	MagnitudeDecayNewFormat(m_windowBuffer,m_fftSize,m_reverbParams);

	IRealFFT_Split(m_windowBuffer,m_fftSize);

	for(S32 uFrame = 0; uFrame < m_reverbParams.hopSize; uFrame++)
	{

		//Re window
		Frame::DoMultiply(m_windowBuffer+((uFrame*uFrameLength)),m_windowBuffer+((uFrame*uFrameLength)),m_pHannBuffer+((uFrame*uFrameLength)));

		//.7875 makes up the gain to the original input signal...maybe FFT is going something funky, never got to the bottom of it
		Frame::Gain(m_windowBuffer+((uFrame*uFrameLength)),m_windowBuffer+((uFrame*uFrameLength)),.7875f * m_ReverbGain);
		int iOffset = ( ((uFrame*uFrameLength))+m_queueBufferReadIndex ) % m_fftSize;
		Frame::DoAdd(m_sumBuffer+iOffset, m_sumBuffer+iOffset, m_windowBuffer+((uFrame*uFrameLength)) );


	}

	Frame::Copy(aSample,m_sumBuffer+m_queueBufferReadIndex);

#ifdef AUDIO_CHECK_SAMPLES
	 for ( U32 uSample = 0; uSample < uFrameLength; uSample++ )
	 {

		if (fabs(aSample[uSample]) > 100.f || !_finite(aSample[uSample]))
			AUDIO_CORE_ERROR(DBSTR" Invalid sample of value %.2f in effect '%s'", aSample[uSample], m_pchInfo);

	 }
#endif // AUDIO_CHECK_SAMPLES

	Frame::Zero(m_sumBuffer+m_queueBufferReadIndex);

	//incremement the read pointer
	m_queueBufferReadIndex += uFrameLength;
	m_queueBufferReadIndex = m_queueBufferReadIndex % (m_fftSize);

	return true;

//#else
//
//return true;
//
//#endif //end ps3

#else
return true;
#endif //end pc

#else // AUDIO_DISABLE_DSP
	return false;
#endif // AUDIO_DISABLE_DSP
}

