//********************************
//RectangularToPolarConversion
//********************************
void Audio::Core::DSP::SpectralReverb::RectangularToPolarConversion(F32 * signal, int fftSize)
{
	//RectangularToPolarConversion 
	// r = sqrt(x*x + y*y)
	// q = arctan(y/x)
	//input:
	//re(0),re(1),re(2),...,re(size/2),im(size/2-1),...,im(1)
	// output:
	//	[MAG],[PHASE],[MAG],[PHASE]....

	int PVSize = fftSize/2;


	F32 *ampbuffer = new F32 [PVSize];
	F32 *phasebuffer = new F32 [PVSize];

	
	for (int i = 0; i <PVSize; i ++)//nbr_points/2
	{
		F32	img = 0;
		F32	real = signal [i];

		if (i > 0)
		{
			img = signal [fftSize-i];
		}
		else
		{
			//because of horrible FFT output format, img[0] == re(size/2), at signal[size/2)
			img = signal [PVSize];
		}

		F32	f_abs = sqrt (real * real + img * img); //magnitude
		F32	f_phase=atan2(img,real);	//phase
		
		ampbuffer[i] = f_abs;//put f_abs in buffer so we can calculate later
		phasebuffer[i] = f_phase;
		
	}

	//output of conversion, PV, is [MAG],[PHASE],[MAG,[PHASE]
	for (int i = 0, k = 0; i < fftSize-2, k < PVSize; i +=2,k++ )//nbr_points/2
	{
		signal[i] =		ampbuffer[k];
		signal[i+1] =	phasebuffer[k];
	}

	delete [] ampbuffer;
	delete [] phasebuffer;

}

