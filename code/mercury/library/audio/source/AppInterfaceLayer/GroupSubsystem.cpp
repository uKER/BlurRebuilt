{
	Group* pGroup = GetGroup(u32GroupIndex);

	if (! pGroup)
		return false;

	pGroup->hType = hType;
}


/////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	PopulateGroupWithEntityInstances
//
/////////////////////////////////////////////////////////////////////////////////////////////////////
bool Audio::GroupSubsystem::PopulateGroupWithEntityInstances(U32 u32NumInstances, U32 u32GroupIndex)
{
	Group* pGroup = GetGroup(u32GroupIndex);

	if (! pGroup)
		return false;

	for (U32 i = 0; i < u32NumInstances; i++)
	{
		EntityInstanceHandle hInstance = CreateEntityInstance(pGroup->hType);
		if (! AddEntityToEndOfList(hInstance, u32GroupIndex))
			return false;
	}

	return true;
}


