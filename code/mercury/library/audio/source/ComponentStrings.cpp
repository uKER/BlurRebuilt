U32 GetComponentType(const char* strLookup)
{
	for (U32 i = 0; i < sizeof(aComponentStringLookup) / sizeof(ComponentStringElement); i++)
	{
		if (strcmp(aComponentStringLookup[i].strName, strLookup) == 0)
			return (U32)(aComponentStringLookup[i].eType);
	}

	return -1;
}


char* GetComponentString(Audio::Component::Types eType)
{
	for (U32 i = 0; i < sizeof(aComponentStringLookup) / sizeof(ComponentStringElement); i++)
	{
		if (aComponentStringLookup[i].eType == eType)
			return aComponentStringLookup[i].strName;
	}

	return 0;
}
