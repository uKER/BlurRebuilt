namespace Debug
{

IMPLEMENT_SUBSCRIBER(EMailSubscriber, "email");

// constructor
EMailSubscriber::EMailSubscriber()
{
	m_sSMTPHost = "";
	m_sUser = "";
	m_sPassword = "";
	m_sSender = "";
	m_sRecipient = "";
	m_sSubject = "Automated Log E-Mail";
	m_triggerLevel = DebugLevel::Error;
	m_iBufferSize = 1024;
	m_iMaxEMails = 1;
	m_iMaxEMailsTimeout = 30;
	m_iLastEmailSentTime = 0;

	m_pFormatter = new LogFormat();
	m_pMutex = new MT::Mutex;
}

// destructor
EMailSubscriber::~EMailSubscriber()
{
	delete m_pFormatter;
	delete m_pMutex;
}

// receive a log event
void EMailSubscriber::Log(LogEvent *pEvent)
{
	m_pMutex->Wait();

	// copy the log event into the buffer
	m_EventBuffer[m_iBufferPos] = *pEvent;
	if (++m_iBufferPos >= m_iBufferSize)
		m_iBufferPos = 0;
	if (m_iBufferPos > m_iBufferUsed)
		m_iBufferUsed = m_iBufferPos;

	m_pMutex->Release();

	// does this event trigger an e-mail to be sent?
	if (pEvent->level > m_triggerLevel)
		return; // no

	// after a certain amount of time, reset the num emails sent counter
	int iCurTime = (int)(Time::GetCurrentTime() / SYS_USEC_PER_SEC);
	if (iCurTime - m_iLastEmailSentTime > m_iMaxEMailsTimeout)
		m_iNumEMailsSent = 0;

	// exceeded m_iMaxEMails ?
	if (m_iMaxEMails != -1 && m_iNumEMailsSent >= m_iMaxEMails)
		return; // yes

	// did we set the required parameters
	if (m_sRecipient == "" || m_sSMTPHost == "")
		return; // no

	SendEMail();
}

/// send an e-mail
void EMailSubscriber::SendEMail()
{
	Network::SMTPClient smtp;

	// connect and login
	smtp.Connect( m_sSMTPHost );
	if (m_sUser != "")
		smtp.Login( m_sUser, m_sPassword );

	// send e-mail header
	smtp.SendEMailHeader( m_sSender, m_sRecipient, m_sSubject );

	// send e-mail body
	smtp.SendEMailBody( Util::C_String( "This e-mail was generated by the Mercury Debug Logging system.\n\n" ) );

	assert(m_EventBuffer.Size() > 0);

	m_pMutex->Wait();

	// loop round the buffer once, formatting and writing out the events as we go
	int i = m_iBufferPos;
	bool bFirst = true;
	do
	{
		if (i >= m_iBufferUsed)
			i = 0;

		if (bFirst)
		{
			m_pFormatter->SetTimeStamp( m_EventBuffer[i].time );
			bFirst = false;
		}

		smtp.SendEMailBody( m_pFormatter->Format( &m_EventBuffer[i] ) );
		i++;
	}
	while (i != m_iBufferPos);

	m_pMutex->Release();

	smtp.FinishEMail();	
	m_iNumEMailsSent++;
	m_iLastEmailSentTime = (int)(Time::GetCurrentTime() / SYS_USEC_PER_SEC);
}

/// parse a configuration parameter for this subscriber
void EMailSubscriber::SetXMLParameter(const char *pName, const char *pValue)
{
	if (!stricmp(pName, "format"))
	{
		Util::C_String value(pValue);
		m_pFormatter->SetFormatString(value);
	}
	else if (!stricmp(pName, "smtphost"))			// set SMTP server hostname
		m_sSMTPHost = Util::C_String( pValue );
	else if (!stricmp(pName, "sender"))				// set e-mail sender
		m_sSender = Util::C_String( pValue );
	else if (!stricmp(pName, "recipient"))			// set e-mail recipient
		m_sRecipient = Util::C_String( pValue );
	else if (!stricmp(pName, "subject"))				// set e-mail subject
		m_sSubject = Util::C_String( pValue );
	else if (!stricmp(pName, "user"))			// set SMTP server username
		m_sUser = Util::C_String( pValue );
	else if (!stricmp(pName, "password"))		// set SMTP server password
		m_sPassword = Util::C_String( pValue );
	else if (!stricmp(pName, "buffersize"))		// set event buffer size
		m_iBufferSize = atoi( pValue );
	else if (!stricmp(pName, "triggerlevel"))	// set e-mail sending trigger level
		m_triggerLevel = DebugLevelFromString( pValue );
	else if (!stricmp(pName, "maxemails"))		// set the maximum number of e-mails to send in one session
	{
		if (!stricmp(pValue, "infinite"))
			m_iMaxEMails = -1;
		else
			m_iMaxEMails = atoi( pValue );
	}
	else if (!stricmp(pName, "maxemailstimeout")) // set timeout before we're allowed to send e-mails again (in seconds)
	{
		m_iMaxEMailsTimeout = atoi( pValue );
	}
}

/// start - dummy function
bool EMailSubscriber::Start()
{
	m_EventBuffer.Resize(m_iBufferSize);
	m_iBufferPos = 0;
	m_iNumEMailsSent = 0;
	m_iBufferUsed = 0;

	return true;
}

};
