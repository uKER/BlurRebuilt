#ifndef __SYSTEM_NETWORK_CONNECTION_H__
#define __SYSTEM_NETWORK_CONNECTION_H__

#pragma once

namespace Sys
{
class Mutex;
}

namespace Network
{

class Service;
class ServiceThread;

/// Represents a connection between the server and client across which communication takes place
class Connection : public Ut::ListElementDouble<Connection>, public Socket
{
	// the derived class should implement functions to handle Pending, Output, Disconnect, etc.

	friend class Service;
	friend class ServiceThread;
public:
					/// Constructor
					Connection(Socket &s);
					/// Default constructor (bodge our way out of error generated by Ut::List. ed will fix)
					Connection();
					/// Destructor
	virtual			~Connection();

					/// Called when data is to be read for this connection
	virtual void	Pending() { };
					/// Called when this connection is ready to receive data
	virtual void	Output() { };
					/// Called on disconnect
	virtual void	Disconnect() { };
					/// Called when the connection has been idle for a set amount of time
	virtual void	Idle() { };

					/// Set whether 'Pending' should be called
	void			SetDetectPending(bool bOn);
					/// Set whether 'Output' should be called
	void			SetDetectOutput(bool bOn);
					/// Set the idle timeout in ms (0 = no not call 'Idle')
	void			SetIdleTimeout(U32 i);

	void			Destroy()
	{
	}

protected:
	bool			m_bDetectPending;
	bool			m_bDetectOutput;
	bool			m_bDetectDisconnect;
	U64				m_iIdleTimeout;
	U64				m_iTimeOfLastIdle;

	// linked list of connections for this service thread
	Connection		*m_pNext;
	Connection		*m_pPrev;

	ServiceThread	*m_pServiceThread;

	MT::Mutex		*m_pMutex;
#if defined(COMPILER_VC)
	HANDLE			m_Event;
#endif
};

};


#endif
