// returns true if this struct should be exported
bool NeedExportStruct(const FxFile::StructDesc *pDesc)
{
	bool bExport = false;
	for (int i=0; i<pDesc->annotations.Size(); i++)
	{
		if (!stricmp(pDesc->annotations[i].Name, "export"))
			return true;
	}
	return false;
}

// write the [ShaderConst...] bit for a particular member variable
bool WriteMember(const FxFile::MemberDesc *pDesc, int *pnFloats, Util::C_String &sHeader, Util::C_String &sBody)
{
	Util::C_String sName = pDesc->name.c_str();

	Util::C_String sAttributes;
	Util::C_String sTmp;
	for (int i=0; i<pDesc->annotations.Size(); i++)
	{
		const FX::Annotation *p = &pDesc->annotations[i];
		if (!stricmp(p->Name, "range"))
		{
			sTmp.Printf("[Range(%s)]", p->String);
			sAttributes += sTmp;
		}		
	}

	if (sName.Length() > 3 && sName[0] == 'm' && sName[1] == '_' &&
		(sName[2] == 'v' || sName[2] == 'f'))
	{
		sName = sName(3, sName.Length()+1);
	}

	const char *pszName = sName.Chars();

	if (!stricmp(pDesc->type.c_str(), "float"))
	{
		// f32
		sHeader.Printf("[ShaderConst(%d, \"%s\")]\n", *pnFloats, pszName);
		sBody.Printf( "%s\tf32 %s;\n", sAttributes.Chars(), pszName);
		(*pnFloats)++;
		return true;
	}

	if (!stricmp(pDesc->type.c_str(), "float2"))
	{
		// Vec2
		sHeader.Printf(	"[ShaderConst(%d, \"%s/x\")]\n"
						"[ShaderConst(%d, \"%s/y\")]\n",
						(*pnFloats), pszName,
						(*pnFloats)+1, pszName);

		sBody.Printf( "%s\tVec2 %s;\n", sAttributes.Chars(), pszName);
		(*pnFloats)+=2;
		return true;
	}

	if (!stricmp(pDesc->type.c_str(), "float3"))
	{
		// Rgb
		sHeader.Printf(	"[ShaderConst(%d, \"%s/r\")]\n"
						"[ShaderConst(%d, \"%s/g\")]\n"
						"[ShaderConst(%d, \"%s/b\")]\n",
						(*pnFloats), pszName,
						(*pnFloats)+1, pszName,
						(*pnFloats)+2, pszName);
		sBody.Printf( "\t[Default(r:\"\",g:\"\",b:\"\")]\n"
					  "%s\tRgb %s;\n", sAttributes.Chars(), pszName);
		(*pnFloats)+=3;
		return true;
	}

	if (!stricmp(pDesc->type.c_str(), "float4"))
	{
		// Rgb
		sHeader.Printf(	"[ShaderConst(%d, \"%s/r\")]\n"
						"[ShaderConst(%d, \"%s/g\")]\n"
						"[ShaderConst(%d, \"%s/b\")]\n"
						"[ShaderConst(%d, \"%s/a\")]\n",
						(*pnFloats), pszName,
						(*pnFloats)+1, pszName,
						(*pnFloats)+2, pszName,
						(*pnFloats)+3, pszName);
		sBody.Printf( "\t[Default(r:\"\",g:\"\",b:\"\",a:\"\")]\n"
					  "%s\tRgba %s;\n", sAttributes.Chars(), pszName);
		(*pnFloats)+=4;
		return true;
	}

	return false;
}

void WriteSchema(FILE *f, const FxFile::StructDesc *pDesc)
{
	Util::C_String tmp, tmp2;
	Util::C_String sHeader, sBody;

	fprintf(f, "// %s\n\n", pDesc->name.c_str());

	// count number of floats
	int nFloats = 0;
	list<FxFile::MemberDesc>::const_iterator iter;
	for (iter = pDesc->members.begin(); iter != pDesc->members.end(); iter++)
	{
		if (!WriteMember(&*iter, &nFloats, tmp, tmp2))
			return; // don't write out structs with matrices or other types that we don't recognise

		sHeader += tmp;
		sBody += tmp2;
	}

	fprintf(f, "[ShaderConstCount(%d)]\n", nFloats);
	fprintf(f, "%s", sHeader.Chars());
	fprintf(f, "type %s_internal\n{\n%s}\n", pDesc->name.c_str(), sBody.Chars());

	fprintf(f, "type %s\n{\n[Tool] [Inline] %s_internal interface;\n\n[Export(method:shaderConst, field:interface)]\n[Hide] f32[] bin;\n}\n",
		pDesc->name.c_str(), pDesc->name.c_str());

	fprintf(f, "\n");
}

bool C_Application::Process(C_Options &options)
{
	// load .FX file
	FxFile fxFile;
	fxFile.Init(options.inputFile.Chars());
	if (!fxFile.isInited)
		return false;

	FILE *f = fopen(options.outputFile.Chars(), "w");
	if (!f)
	{
		LOGFATAL( m_log, "Couldn't open file '%s': %s\n", options.outputFile.Chars(), strerror(NULL));
		return false;
	}

	fprintf(f, "// Schema for %s.\n// Please do not edit this file.\n// It has been automatically generated by SorceryFX.\n\n", options.inputFile.Chars());

	// for each struct, write out a bit of sorcery schema
	list<FxFile::StructDesc>::const_iterator iter;
	for (iter = fxFile.structDescs.begin(); iter != fxFile.structDescs.end(); iter++)
	{
		if (NeedExportStruct(&*iter))
			WriteSchema(f, &*iter);
	}

	fclose(f);

	return true;
}

S32 C_Application::Main(S32 argc, char **argv, Progress::I_ProgressBar *pProgress)
{
	C_Options options;
	bool success = true;

	//Build options struct
	{
		//Parse our command-line options.
		success = ParseCommandLineOptions(argc, argv, options);
		if (!success) goto exit;
	}

	success = Process(options);
exit:
	if (success)
	{
//		EXECUTER_INFO("Processing completed succesfully!\n");
	}
	else
	{
//		EXECUTER_INFO("Processing failed!\n");
	}

	if (success)
		return 0;
	else
		return 1;
}

bool C_Application::ParseCommandLineOptions(
	int argc, 
	char* argv[], 
	C_Options& options)
{
	// Wrap everything in a try block.  Do this every time, 
	// because exceptions will be thrown for problems. 
	try
	{  
		//Define the command line object.
		TCLAP::CmdLine cmd(GetName(), GetSubtitle(), "1.00");

		//Define a value argument and add it to the command line.
		TCLAP::UnlabeledValueArg<std::string> inputArg("input","Name of the .FX file or .H file to be converted","","input");
		cmd.add(inputArg);
		TCLAP::UnlabeledValueArg<std::string> outputArg("output","Name of the output schema","","output");
		cmd.add(outputArg);

		//Parse the args.
		cmd.parse(argc, argv);

		//Get the values
		options.inputFile = inputArg.getValue().c_str();
		options.outputFile = outputArg.getValue().c_str();
	} 
	catch (TCLAP::CmdLineParseException &e)
	{
		std::cerr << "Failed to parse arguments: " << e.argId() << std::endl;
		return false;
	}
	catch (TCLAP::ArgException &e)  // catch any exceptions
	{ 
		std::cerr << "Error: " << e.error() << " for arg " << e.argId() << std::endl;
		return false;
	}

	return true;
}
