//Manager for the Demonware Key Archive
class C_KeyArchiveManager
{
public:
	
	C_KeyArchiveManager()
	{
		mCurrentTaskType=KEY_ARCHIVE_TASK_TYPE_NOTHING;
		mLastRequestFailed=false;
		mKeysToWrite.Resize(0);
		mKeysRead.Resize(KEY_ARCHIVE_INDEX_KEY_MAX);
		mKeyBuffer.Resize(KEY_ARCHIVE_INDEX_KEY_MAX);
	};
	
	//must be called before all usage of the key archive
	bool IsActive(){return RacerNet::C_NetServices::Instance().Router().GetKeyArchive() ? true : false;};

	//per frame update function
	void Update();

	//sets the user index for the current user of the key archive
	bool SetUserIndex(U8 index);

	void SetDemonwareId(bdOnlineUserID id);
	
	//functions to add to key archive, Clear -> Recurse Add and then Write will write it all out
	bool ClearKeyArchiveToWrite();
	bool AddKeyArchivePairToWrite(KEY_ARCHIVE_INDEX_KEY key, bdInt64 value, bdKeyValuePair::bdArchiveUpdateType update_type=bdKeyValuePair::BD_REPLACE);
	bool WriteKeyArchive();
	
	//function to read the key archive back into the mKeyArchivePairs
	bool ReadKeyArchive();

	//function to read a selection of key archives back into the mKeyArchivePairs
	bool ReadKeyArchiveSubset(int start, int size);

	//gets a value from the key, can be used after a read or to ask again before a write
	bdInt64 GetValueFromKey(KEY_ARCHIVE_INDEX_KEY key){return mKeyBuffer[key];};

	// pump the current task, returns false when finished, errors are returned by passing in a bool pointer (this will turn to an enum soon)
	bool PumpCurrentTask(bool *error);

	//kill the current task
	void KillCurrentTask();

	//return the instance
	static C_KeyArchiveManager& Instance(){return s_instance;}

	const KEY_ARCHIVE_TASK_TYPE GetCurrentTaskType() const;

	bool GetLastRequestFailed() const;

private:
	void KillCurrentTaskInternal();

	void ProcessReadKeys();
	
	void ProcessReadKeysSubset();
	
	static C_KeyArchiveManager s_instance;
	
	//stores the current task type, so we can deal with the results effectively
	KEY_ARCHIVE_TASK_TYPE mCurrentTaskType;

	//user information
	bdOnlineUserID mDemonWareUserID;

	Btl::Vector<bdKeyValuePair> mKeysToWrite;
	Btl::Vector<bdKeyValuePair> mKeysRead;
	Btl::Vector<U64> mKeyBuffer;

	// used for tracking reads and writes
	bdRemoteTaskRef mAsyncTask;

	//finish the current task
	void FinishCurrentTask();

	bool mLastRequestFailed;

	int mSubsetStart;
	int mSubsetCount;
};


