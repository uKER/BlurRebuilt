struct RasterizedTriInfo
{
public:
	// variables for calculate barycentric coordinates
	/// **** DO NOT CHANGE THIS STRUCTURE WITHOUT CHANGING RasterizedTriIterator::SetInfo
	float				m_b0;
	float				m_x1,m_x2,m_x3,m_y1,m_y2,m_y3;

	float3				m_vPos[3];
	float3				m_vNormal[3];
	bool				m_bClampEdge[3];
	float3				m_vPlane[3];
	float3				m_vTangent[3];
	float3				m_vBinormal[3];

	// rasterization info
	int					m_iFirstEdgeY;
	int					m_nEdges;
	int					m_iRasterizedEdge;

	short				m_x, m_y, m_cx, m_cy;
};

