// Edge	structure.
typedef	struct
{
	int	idx0;
	int	idx1;

	// Min/max info
	float yMin;
	float yMax;
	float x;
	float x1;
	float increment;
	float numerator;
	float denominator;
	float dx_over_dy;
} NmEdge;

typedef union
{
   struct { float u, v; };
   struct { float uv[2]; };
} NmRawTexCoord;

struct NmRawTriangle
{
	float3 vert[3];
	float3 norm[3];
	NmRawTexCoord texCoord[3];
	short  m_x, m_y, m_cx, m_cy;
	// tangent space
	float3 tangent[3];
	float3 binormal[3];

	friend ost::Engine& operator >> (ost::Engine& ar, NmRawTriangle &ti)
	{
		ar >> ti.vert[0] >> ti.vert[1] >> ti.vert[2];
		ar >> ti.norm[0] >> ti.norm[1] >> ti.norm[2];
		ar >> ti.texCoord[0].u >> ti.texCoord[0].v;
		ar >> ti.texCoord[1].u >> ti.texCoord[1].v;
		ar >> ti.texCoord[2].u >> ti.texCoord[2].v;
		ar >> ti.m_x >> ti.m_y >> ti.m_cx >> ti.m_cy;

		ar >> ti.tangent[0] >> ti.tangent[1] >> ti.tangent[2];
		ar >> ti.binormal[0] >> ti.binormal[1] >> ti.binormal[2];

		return ar;
	}
	friend ost::Engine& operator << (ost::Engine& ar, NmRawTriangle &ti) 
	{ 
		ar << ti.vert[0] << ti.vert[1] << ti.vert[2];
		ar << ti.norm[0] << ti.norm[1] << ti.norm[2];
		ar << ti.texCoord[0].u << ti.texCoord[0].v;
		ar << ti.texCoord[1].u << ti.texCoord[1].v;
		ar << ti.texCoord[2].u << ti.texCoord[2].v;
		ar << ti.m_x << ti.m_y << ti.m_cx << ti.m_cy;

		ar << ti.tangent[0] << ti.tangent[1] << ti.tangent[2];
		ar << ti.binormal[0] << ti.binormal[1] << ti.binormal[2];

		return ar;
	}
};

#include "Lux/SurfaceIterator.h"

struct RasterizedEdge
{
	int x1,x2;

	friend ost::Engine& operator >> (ost::Engine& ar, RasterizedEdge &e) { ar >> e.x1 >> e.x2; return ar; }
	friend ost::Engine& operator << (ost::Engine& ar, RasterizedEdge &e) { ar << e.x1 << e.x2; return ar; }
};

