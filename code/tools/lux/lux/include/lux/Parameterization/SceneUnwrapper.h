#ifndef LUX_SCENE_UNWRAPPER_H
#define LUX_SCENE_UNWRAPPER_H

class LightingPass;
namespace Progress
{
	class I_ProgressBar;
};

namespace LUX
{
	class SceneUnwrapper
	{
	public:
		SceneUnwrapper();
		~SceneUnwrapper();

		/// unwrap the entire scene into texture charts, chart list is stored in _m_ChartList_
		bool			Unwrap(	Aftk::C_Scene* pAftkScene,
								const LightingModelProperties *pProp,
								const Ut::Vector<LightingPass*> *pLightingPasses,
								bool bStoreMatrices,
								Progress::I_ProgressBar *pProgress);
		void			Purge();
		void			SetChartNumbersToPolygons();
		Aftk::C_SceneNode	*InstantiateMeshNode(Aftk::C_SceneInstanceNode *pNode, LightingPass *pCurPass);
		void			SetDoubleSidedPolyflagMask(int iDoubleSidedPolyflagMask);
		void			SetDoNotLightPolyflagMask(int iDoNotLightPolyflagMask);
		void			SetLowResLightmapPolyflagMask(int iLowResLightmapPolyflag);
		void			SetLowResLightmapBits(int iBits);
		void			SetCalculateTangentSpace(bool bOn);
		void			SetSeamSettings(bool bFixSeams, bool bFixAllSeams);

		TChartList	m_ChartList;			// list of charts generated by the unwrapper
		TChartMatrixList m_ChartMatrixList;	// contains the world-to-uv matrix of each chart
		TSeamGroupList m_SeamGroups;		// list of groups of charts that have common edges with potential seams

		float		m_fScale;				// texture scale - must be set before calling Unwrap
		float		m_fTexelDensityRatio[5];		// alternate texel density scale ratio (high, normal, low, very low)

		float		m_fMaxSize;

	private:
		SceneUnwrapper(const SceneUnwrapper& rhs);
		const SceneUnwrapper& operator=(const SceneUnwrapper& rhs);
		int			m_iDoubleSidedPolyflagMask;
		int			m_iDoNotLightPolyflagMask;
		int			m_iLowResLightmapPolyflag;
		int			m_iLowResLightmapBits;
		bool		m_bCalculateTangentSpace;
		bool		m_bFixSeams, m_bFixAllSeams;

	};
}

#endif
